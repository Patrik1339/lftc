import { Grammar, Sym, isNT } from './types';

/**
 * Does g derive the word w? Computes, as a least fixpoint, which spans w[i..j) each nonterminal derives,
 * so it works for any grammar (ε-productions, renames, cycles, left recursion).
 */
export function derives(g: Grammar, w: Sym[]): boolean {
  const n = w.length;
  const spans = new Map<Sym, Set<number>[]>(g.nonterminals.map((A) => [A, Array.from({ length: n + 1 }, () => new Set<number>())]));
  let changed = true;
  while (changed) {
    changed = false;
    for (const A of g.nonterminals) {
      for (const rhs of g.prods[A]) {
        for (let i = 0; i <= n; i++) {
          let pos = new Set([i]);
          for (const X of rhs) {
            const next = new Set<number>();
            const sx = spans.get(X);
            for (const p of pos) {
              if (sx) sx[p].forEach((j) => next.add(j));
              else if (p < n && w[p] === X) next.add(p + 1);
            }
            pos = next;
            if (!pos.size) break;
          }
          const target = spans.get(A)![i];
          for (const j of pos) {
            if (!target.has(j)) {
              target.add(j);
              changed = true;
            }
          }
        }
      }
    }
  }
  return spans.get(g.start)?.[0].has(n) ?? false;
}

/** All words of length ≤ n generated by g (terminals are single characters), shortest first. */
export function wordsUpTo(g: Grammar, n: number): string[] {
  const L = new Map<Sym, Set<string>>(g.nonterminals.map((A) => [A, new Set<string>()]));
  let changed = true;
  while (changed) {
    changed = false;
    for (const A of g.nonterminals) {
      for (const rhs of g.prods[A]) {
        let cur = new Set(['']);
        for (const X of rhs) {
          const next = new Set<string>();
          const parts = isNT(g, X) ? L.get(X)! : [X];
          for (const u of cur) for (const v of parts) if ([...u].length + [...v].length <= n) next.add(u + v);
          cur = next;
          if (!cur.size) break;
        }
        const target = L.get(A)!;
        for (const w of cur) {
          if (!target.has(w)) {
            target.add(w);
            changed = true;
          }
        }
      }
    }
  }
  return [...(L.get(g.start) ?? [])].sort((a, b) => [...a].length - [...b].length || a.localeCompare(b));
}
